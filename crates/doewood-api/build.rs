//! Compiles `proto/doewood/v1/*.proto` with protox (pure Rust, so `cargo build` needs no
//! `protoc`), generates the tonic servers and clients, and writes the encoded descriptor set
//! that gRPC reflection serves, and the sorted list of method paths the request metrics label
//! calls with (`grpc_methods.rs`).

use std::fmt::Write as _;
use std::path::PathBuf;

use prost::Message as _;

const FILES: &[&str] = &[
    "doewood/v1/common.proto",
    "doewood/v1/config.proto",
    "doewood/v1/jobs.proto",
    "doewood/v1/records.proto",
    "doewood/v1/graph.proto",
    "doewood/v1/search.proto",
    "doewood/v1/summarize.proto",
    "doewood/v1/ingest.proto",
];

/// The methods of the health and reflection services (tonic-health, tonic-reflection).
const HEALTH_AND_REFLECTION: &[&str] = &[
    "/grpc.health.v1.Health/Check",
    "/grpc.health.v1.Health/Watch",
    "/grpc.reflection.v1.ServerReflection/ServerReflectionInfo",
    "/grpc.reflection.v1alpha.ServerReflection/ServerReflectionInfo",
];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?).join("../../proto");
    println!("cargo:rerun-if-changed={}", root.display());
    let files: Vec<PathBuf> = FILES.iter().map(|f| root.join(f)).collect();
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
    }
    let fds = protox::compile(&files, [&root])?;
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out.join("doewood_v1_descriptor.bin"), fds.encode_to_vec())?;
    let mut methods: Vec<String> = HEALTH_AND_REFLECTION
        .iter()
        .map(|m| (*m).to_owned())
        .collect();
    for file in &fds.file {
        for service in &file.service {
            for method in &service.method {
                methods.push(format!(
                    "/{}.{}/{}",
                    file.package(),
                    service.name(),
                    method.name()
                ));
            }
        }
    }
    methods.sort();
    methods.dedup();
    let mut list = String::from(
        "/// Every gRPC method path served, sorted (generated by build.rs).\n\
         pub(crate) const METHODS: &[&str] = &[\n",
    );
    for m in &methods {
        writeln!(list, "    {m:?},")?;
    }
    list.push_str("];\n");
    std::fs::write(out.join("grpc_methods.rs"), list)?;
    tonic_prost_build::configure()
        .build_server(true)
        .build_client(true)
        .compile_fds(fds)?;
    Ok(())
}
